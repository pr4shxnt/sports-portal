import mongoose, { Document, Schema } from "mongoose";

/**
 * Match centre record for one Champions League fixture. The fixture itself
 * lives in a Draw (`matchId` is the draw's fixture id); this adds the
 * schedule, the event timeline and the shootout. The score is always derived
 * from the events and written back to the draw, so tables and brackets keep
 * working unchanged.
 */
export const MATCH_STATUSES = ["scheduled", "live", "finished"] as const;
export type MatchStatus = (typeof MATCH_STATUSES)[number];

export const EVENT_TYPES = [
  "goal",
  "penalty_goal", // penalty for a foul in the area, scored (§12.1)
  "own_goal", // `team` = the scorer's team; the goal counts for the opponent
  "penalty_missed", // `saved` marks a goalkeeper save
  "yellow",
  "red",
] as const;
export type EventType = (typeof EVENT_TYPES)[number];

/** Regulation time is two halves of 25 minutes on a stopped clock (§11.1). */
export const HALF_MINUTES = 25;
export const MATCH_MINUTES = 2 * HALF_MINUTES;

export interface IMatchEvent {
  _id: mongoose.Types.ObjectId;
  type: EventType;
  /**
   * The player's team. For an own goal that is the team that conceded, so
   * the goal is credited to the opponent.
   */
  team: mongoose.Types.ObjectId;
  player?: mongoose.Types.ObjectId;
  minute: number; // 1–50 on the match clock
  saved?: boolean; // penalty_missed: saved by the goalkeeper
  /** Red card generated by a second yellow in the same match (§13.1). */
  secondYellow?: boolean;
  /** For an auto red: the yellow that triggered it. */
  causedBy?: mongoose.Types.ObjectId;
}

export interface IShootoutKick {
  _id: mongoose.Types.ObjectId;
  team: mongoose.Types.ObjectId;
  player?: mongoose.Types.ObjectId;
  scored: boolean;
  saved?: boolean;
}

export interface IMatch extends Document {
  competition: mongoose.Types.ObjectId;
  draw: mongoose.Types.ObjectId;
  matchId: string;
  home: mongoose.Types.ObjectId;
  away: mongoose.Types.ObjectId;
  knockout: boolean;
  kickoff?: Date;
  venue?: string;
  status: MatchStatus;
  events: IMatchEvent[];
  shootout: IShootoutKick[];
  /** Team that forfeited (§9.6): recorded as a 3–0 win for the opponent. */
  forfeitedBy?: mongoose.Types.ObjectId | null;
  createdAt: Date;
  updatedAt: Date;
}

const EventSchema = new Schema<IMatchEvent>({
  type: { type: String, enum: EVENT_TYPES, required: true },
  team: { type: Schema.Types.ObjectId, ref: "Team", required: true },
  player: { type: Schema.Types.ObjectId, ref: "Player" },
  minute: { type: Number, min: 1, max: MATCH_MINUTES, required: true },
  saved: Boolean,
  secondYellow: Boolean,
  causedBy: Schema.Types.ObjectId,
});

const KickSchema = new Schema<IShootoutKick>({
  team: { type: Schema.Types.ObjectId, ref: "Team", required: true },
  player: { type: Schema.Types.ObjectId, ref: "Player" },
  scored: { type: Boolean, required: true },
  saved: Boolean,
});

const MatchSchema = new Schema<IMatch>(
  {
    competition: {
      type: Schema.Types.ObjectId,
      ref: "Competition",
      required: true,
    },
    draw: { type: Schema.Types.ObjectId, ref: "Draw", required: true },
    matchId: { type: String, required: true },
    home: { type: Schema.Types.ObjectId, ref: "Team", required: true },
    away: { type: Schema.Types.ObjectId, ref: "Team", required: true },
    knockout: { type: Boolean, default: false },
    kickoff: Date,
    venue: { type: String, trim: true },
    status: { type: String, enum: MATCH_STATUSES, default: "scheduled" },
    events: { type: [EventSchema], default: [] },
    shootout: { type: [KickSchema], default: [] },
    forfeitedBy: { type: Schema.Types.ObjectId, ref: "Team", default: null },
  },
  { timestamps: true },
);

MatchSchema.index({ draw: 1, matchId: 1 }, { unique: true });
MatchSchema.index({ competition: 1, kickoff: 1 });

export default mongoose.model<IMatch>("Match", MatchSchema);
